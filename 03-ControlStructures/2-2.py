
size = input('Enter size symbol: ')

if size == 'S' or size == 's':
    print('S: Small size')
elif size == 'M' or size == 'm':
    print('M: Medium size')
elif size == 'L' or size =='l':
    print('L: Large size')
elif size == 'XL' or size == 'xl':
    print('XL: Extra large size')
else:
    print('Inorrect symbol')
